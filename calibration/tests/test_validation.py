def _rodrigues(w):
    th = math.sqrt(float(w @ w))
    if th < 1e-12:
        return np.eye(3)
    k = w / th
    K = np.array([[0, -k[2], k[1]], [k[2], 0, -k[0]], [-k[1], k[0], 0]])
    return np.eye(3) + math.sin(th) * K + (1 - math.cos(th)) * (K @ K)


def model_recording(seconds=60.0, rate=10.0, seed=0):
    """A recording the model itself produced: command steps on surge, sway, heave and yaw (and a little roll), with
    its own orientation. Integrated independently of validation.py: dynamics_model's rotation-matrix physics and a
    rotation matrix, at the calibration's own 0.005 s step."""
    rng = np.random.default_rng(seed)
    n = int(seconds * rate)
    dt = 1 / rate
    F = np.zeros((n, 6))
    for j, size in ((0, 25.0), (1, 15.0), (2, 12.0), (5, 3.0)):
        level = 0.0
        for k in range(n):
            if k % int(6 * rate) == 0:
                level = size * rng.choice([-1, 0, 1])
            F[k, j] = level
    F[:, 3] = 0.05 * np.sin(np.arange(n) * dt)
    R = Rotation.from_euler("xyz", [0.02, -0.03, 0.4]).as_matrix()
    v = np.zeros(6)
    sub = 20
    h = dt / sub
    nu, quat = np.empty((n, 6)), np.empty((n, 4))
    for k in range(n):
        nu[k], quat[k] = v, Rotation.from_matrix(R).as_quat()
        for _ in range(sub):
            v = v + h * compute_acceleration_from_rotation_matrix(TRUTH, SPEC.vehicle, v, F[k], R)[0]
            R = R @ _rodrigues(v[3:] * h)
    rp = Rotation.from_quat(quat).as_euler("xyz")[:, :2]
    return RunData(filepath="model-01-01-2030-run1.csv", forces_torques=F, roll_pitch=rp, real_nu=nu,
                   nu0=nu[0].copy(), dt=dt, sample_rate_hz=rate, orientation_quat=quat)


RUN = model_recording()


def test_path_from_velocity_turns_body_velocity_into_world_positions():
    q = np.tile(Rotation.from_euler("xyz", [0, 0, math.pi / 2]).as_quat(), (11, 1))
    p = V.path_from_velocity(np.tile([1.0, 0, 0], (11, 1)), q, 0.1)
    assert np.allclose(p[-1], [0, 1.0, 0], atol=1e-9)  # heading 90 deg: forward is world +y


def test_the_model_replaying_its_own_recording_has_near_zero_error_and_the_baselines_dont():
    models = {"calibrated": TRUTH}
    drift = V.trajectory_drift(models, [RUN], SPEC.vehicle, horizons_s=(10, 30))
    for i in range(2):
        assert drift["calibrated"][i]["p90"] < 0.01, drift["calibrated"][i]  # the two simulators agree
        assert drift["no_motion"][i]["median"] > 0.3
    ori = V.orientation_error(models, [RUN], SPEC.vehicle)
    for name in ("roll", "pitch", "yaw"):
        assert ori["calibrated"][name][-1]["p90"] < 0.01, (name, ori["calibrated"][name])
    assert ori["hold_start"]["yaw"][-1]["median"] > 10
    resp = V.response_error(models, [RUN], SPEC.vehicle)
    sk = np.array(resp["calibrated"]["skill_vs_same_velocity"])
    assert (sk[[0, 1, 2, 5]] > 0.9).all(), sk


def test_command_steps_are_found_and_the_true_model_matches_their_response():
    s = V.step_responses({"calibrated": TRUTH}, [RUN], SPEC.vehicle)["summary"]
    for ax in ("u", "v", "w", "r"):
        assert s[ax]["steps"] >= 2, (ax, s[ax])
        assert s[ax]["calibrated_size_ratio"] == pytest.approx(1.0, abs=0.1)
        assert s[ax]["calibrated_rise_s"] == pytest.approx(s[ax]["real_rise_s"], abs=0.15)


def test_find_steps_ignores_ramps_and_noise():
    rng = np.random.default_rng(1)
    F = np.concatenate([np.zeros(30), np.full(40, 10.0), np.linspace(10, 30, 40), np.full(40, 30.0)])
    F = F + rng.normal(0, 0.1, len(F))
    assert V.find_steps(F, 10.0, 3.0) == [30]


def test_a_wrong_model_shows_up_as_drift_and_slow_or_fast_steps():
    wrong = CalibrationParameters(**{**{n: getattr(TRUTH, n) for n in TRUTH.param_names}, "Xu": TRUTH.Xu * 4})
    drift = V.trajectory_drift({"calibrated": wrong}, [RUN], SPEC.vehicle, horizons_s=(10,))
    assert drift["calibrated"][0]["median"] > 0.2
    s = V.step_responses({"calibrated": wrong}, [RUN], SPEC.vehicle)["summary"]["u"]
    assert s["calibrated_size_ratio"] < 0.8  # four times the slow-speed drag: a smaller surge response


def test_validate_writes_numbers_plots_and_a_report_section(tmp_path):
    """The whole step on files: a 'calibration' that is the model itself, its recordings as CSVs."""
    pytest.importorskip("matplotlib")
    import pandas as pd
    import yaml
    from calibration_report import build_report
    data = tmp_path / "logs"
    data.mkdir()
    for i, (date, seed) in enumerate((("01-01-2030", 0), ("02-01-2030", 1), ("03-01-2030", 2))):
        run = model_recording(40.0, seed=seed)
        df = pd.DataFrame(run.forces_torques, columns=["Fx", "Fy", "Fz", "Tx", "Ty", "Tz"])
        df[["Bu", "Bv", "Bw", "Bp", "Bq", "Br"]] = run.real_nu
        df[["qx", "qy", "qz", "qw"]] = run.orientation_quat
        df.to_csv(data / f"model-{date}-run1.csv", index=False)
    res = tmp_path / "result"
    res.mkdir()
    (res / "calibrated_parameters.yaml").write_text(yaml.safe_dump(
        {"parameters": {n: float(getattr(TRUTH, n)) for n in TRUTH.param_names}}))
    zero = [1.0] * 6
    (res / "metrics.json").write_text(json.dumps({
        "dataset": {"heldout_dates": ["03-01-2030"]},
        "objective": {"sampling_rate_hz": 10.0, "torque_reference_offset_m": [0, 0, 0]},
        "per_dof": {"default_heldout": zero, "calibrated_heldout": [0.1] * 6, "calibrated_train": [0.1] * 6},
        "rmse": {"calibrated_train": 0.1, "calibrated_heldout": 0.1},
        "skill_vs_zero": {"zero_heldout": zero, "calibrated_heldout_full_replay": [0.9] * 6}}))
    assert V.main(["--result", str(res), "--data-dir", str(data), "--spec",
                   os.path.join(CAL, "vehicle_spec.yaml")]) == 0
    out = json.loads((res / "validation" / "validation.json").read_text(encoding="utf-8"))
    assert out["heldout_recordings"] == 1 and out["heldout_dates"] == ["03-01-2030"]
    for p in ("velocity_typical.png", "trajectory_typical.png", "drift.png", "orientation_typical.png"):
        assert p in out["plots"] and (res / "validation" / p).stat().st_size > 10_000, p
    build_report(str(res), os.path.join(CAL, "vehicle_spec.yaml"))
    report = (res / "calibration_report.md").read_text(encoding="utf-8")
    assert "## How the simulation compares with the real vehicle" in report
    assert "![Position drift against horizon](validation/drift.png)" in report
    assert "| 10 s |" in report and "| Yaw |" in report


def test_report_says_which_angles_to_distrust():
    from calibration_report import validation_section
    s = lambda m: {"n": 10, "median": m, "p25": m, "p75": m, "p90": m}
    v = {"heldout_recordings": 2, "heldout_dates": ["d"], "plots": [],
         "trajectory": {"horizons_s": [10], "calibrated": [s(0.8)], "default": [s(3)], "no_motion": [s(3)],
                        "diverged": {"calibrated": [0]}},
         "orientation": {"report_s": [3, 10], "window_s": 10, "windows": 5, "diverged": {"calibrated": 0},
                         "calibrated": {"roll": [s(5), s(9)], "pitch": [s(5), s(11)], "yaw": [s(17), s(40)]},
                         "default": {"roll": [s(18), s(20)], "pitch": [s(18), s(17)], "yaw": [s(50), s(80)]},
                         "hold_start": {"roll": [s(3), s(4)], "pitch": [s(5), s(6)], "yaw": [s(37), s(95)]}},
         "response": {"horizon_s": 1.0, "windows": 100, "diverged": {"calibrated": 0}, "same_velocity_rmse": [1] * 6,
                      "calibrated": {"rmse": [0.5] * 6, "skill_vs_same_velocity": [0.5] * 6},
                      "default": {"rmse": [1] * 6, "skill_vs_same_velocity": [0] * 6}},
         "steps": {"u": {"steps": 9, "real_rise_s": 0.6, "calibrated_rise_s": 0.3, "calibrated_size_ratio": 1.0}}}
    text = "\n".join(validation_section(v))
    assert "**Yaw:** the simulation tracks the real vehicle better" in text
    assert "**Roll, pitch:** worse than simply holding the starting attitude" in text
    assert "responds faster than the real one:** at least 1.5 times as fast on 1 of 1 axes" in text
    v["steps"]["v"] = {"steps": 5, "real_rise_s": 0.6, "calibrated_rise_s": 0.5, "calibrated_size_ratio": 1.0}
    assert "responds faster" not in "\n".join(validation_section(v))  # 1 of 2 is not a majority


def test_strathe_validate_and_calibrate_run_the_comparison():
    import strathe_cli as cli
    calls = []
    assert cli.main(["validate", "--result", "out"], runner=lambda c: calls.append(c[1:]) or 0) == 0
    assert calls[0][0] == "validation.py" and calls[1][0] == "calibration_report.py"
    calls.clear()
    cli.main(["calibrate", "--data", CAL, "--out", "/tmp/x", "--skip-identifiability"],
             runner=lambda c: calls.append(c[1:]) or 0)
    names = [c[0] for c in calls]
    assert names.index("validation.py") == names.index("calibration_report.py") - 1
